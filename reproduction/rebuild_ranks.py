#!/usr/bin/env python3
"""Rebuild the mean ranks of the main comparison from the per-seed records (no model is run).

  python reproduction/rebuild_ranks.py [--rank_on unrounded|displayed] [--out results]

Reads  reproduction/main_per_seed_k20.csv (270 rows: 9 settings x (9 methods + STFR (forecast))
       x seeds 20/21/22)
Writes <out>/main_means_k20.csv, main_column_ranks_k20.csv, main_mean_rank_k20.csv and
       MEAN_RANK_K20.md (displayed value and rank per column, mean rank per backbone)

The three seeds are averaged first (unrounded); every accuracy column (Recall@20, NDCG@20)
is ranked within its setting and the mean rank averages the 6 columns (three datasets x two
metrics) of each backbone; the overall mean rank averages the three backbones.  The nine
methods are ranked among themselves; STFR (forecast) is ranked against the other eight with
STFR removed.  Ranks use the unrounded means, as in the manuscript; --rank_on displayed ranks
the printed four-decimal values with average ranks for equal displayed values (it changes
the ranks of methods that print the same value as another method in a column).  The functions
are those of analysis/common.py used by analysis/collect_results.py.
"""
import argparse
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'analysis'))
from common import display_ranks, check_records, MAIN_ARMS, VARIANT_ARMS, RANK_COLUMNS, CELL_ORDER, label  # noqa: E402

METRICS = ['recall20', 'ndcg20']


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--rank_on', default='unrounded', choices=('unrounded', 'displayed'))
    p.add_argument('--out', default='results')
    a = p.parse_args()
    os.makedirs(a.out, exist_ok=True)
    seeds = pd.read_csv(os.path.join(HERE, 'main_per_seed_k20.csv'))
    arms = MAIN_ARMS + VARIANT_ARMS
    problems = check_records(seeds, arm_col='method', arms=arms, keys=('dataset', 'backbone'))
    if problems or len(seeds) != 270:
        raise SystemExit('main_per_seed_k20.csv: %d rows\n%s' % (len(seeds), '\n'.join(problems)))
    means = seeds.groupby(['dataset', 'backbone', 'method']).agg(
        n_seeds=('seed', 'count'), recall20=('recall20', 'mean'), ndcg20=('ndcg20', 'mean'),
        nalrp20=('nalrp20', 'mean')).reset_index()
    means.to_csv(os.path.join(a.out, 'main_means_k20.csv'), index=False, float_format='%.10f')

    ranked, mr = display_ranks(means[means.method.isin(MAIN_ARMS)], METRICS, ['dataset', 'backbone'],
                               arm_col='method', on=a.rank_on)
    parts, mrs = [ranked], [mr.assign(ranked_against='nine methods')]
    for v in VARIANT_ARMS:
        rv, mv = display_ranks(means[means.method.isin([x for x in MAIN_ARMS if x != 'STFR'] + [v])], METRICS,
                               ['dataset', 'backbone'], arm_col='method', on=a.rank_on)
        parts.append(rv[rv.method == v])
        mrs.append(mv[mv.method == v].assign(ranked_against='eight other methods, STFR removed'))
    ranked = pd.concat(parts, ignore_index=True)
    mr = pd.concat(mrs, ignore_index=True)
    cols = []
    for m in METRICS:
        c = ranked[['dataset', 'backbone', 'method']].copy()
        c.insert(2, 'metric', m)
        c['value'] = ranked[m].map(lambda v: '%.10f' % v)
        c['displayed'] = ranked['disp_' + m]
        c['rank'] = ranked['rank_' + m]
        cols.append(c)
    cols = pd.concat(cols)
    cols['_c'] = [CELL_ORDER.index((d, b)) for d, b in zip(cols.dataset, cols.backbone)]
    cols['_a'] = cols.method.map(arms.index)
    cols = cols.sort_values(['_c', 'metric', '_a'], kind='stable').drop(columns=['_c', '_a'])
    cols.to_csv(os.path.join(a.out, 'main_column_ranks_k20.csv'), index=False)

    mr = mr.rename(columns={'mean_rank_n_cols': 'n_cols'})[['backbone', 'method', 'n_cols', 'mean_rank', 'ranked_against']]
    bad = mr[mr.n_cols != mr.backbone.map(RANK_COLUMNS)]
    if not bad.empty:
        raise SystemExit('unexpected number of rank columns:\n%s' % bad.to_string(index=False))
    overall = mr.groupby('method', sort=False).agg(mean_rank=('mean_rank', 'mean'), n_cols=('n_cols', 'sum'),
                                                   ranked_against=('ranked_against', 'first')).reset_index()
    overall['backbone'] = 'all'
    out = pd.concat([mr, overall[mr.columns]], ignore_index=True)
    out['_b'] = out.backbone.map(['MF', 'LightGCN', 'SimGCL', 'all'].index)
    out['_a'] = out.method.map(arms.index)
    out = out.sort_values(['_b', '_a']).drop(columns=['_b', '_a'])
    out.to_csv(os.path.join(a.out, 'main_mean_rank_k20.csv'), index=False)

    short = {'Amazon-VG': 'VG', 'Amazon-Movies': 'Movies', 'Douban-movie': 'Douban'}
    md = ['# Mean rank of the main comparison (test @20, three-seed means)', '',
          'Generated by `reproduction/rebuild_ranks.py` from `main_per_seed_k20.csv` (ranks on the %s means).' % a.rank_on,
          'The nine methods are ranked among themselves; STFR (forecast) is ranked against the other eight',
          'methods with STFR removed.  Values are the displayed four-decimal three-seed means.', '']
    for bb in ('MF', 'LightGCN', 'SimGCL'):
        dss = [d for d, b in CELL_ORDER if b == bb]
        md += ['## %s' % bb, '',
               '| Method | ' + ' | '.join('%s %s (rank)' % (short[d], x) for d in dss for x in ('R@20', 'N@20')) + ' | mean rank |',
               '|---' * (2 * len(dss) + 2) + '|']
        for arm in arms:
            cells = []
            for d in dss:
                for m in METRICS:
                    r = cols[(cols.dataset == d) & (cols.backbone == bb) & (cols.method == arm) & (cols.metric == m)]
                    cells.append('%s (%g)' % (r.displayed.iloc[0], r['rank'].iloc[0]) if len(r) else '-')
            q = out[(out.backbone == bb) & (out.method == arm)]
            md.append('| %s | %s | %.2f |' % (label(arm), ' | '.join(cells), q.mean_rank.iloc[0]))
        md.append('')
    md += ['## Over the three backbones', '', '| Method | mean rank |', '|---|---|']
    for arm in arms:
        q = out[(out.backbone == 'all') & (out.method == arm)]
        md.append('| %s | %.2f |' % (label(arm), q.mean_rank.iloc[0]))
    open(os.path.join(a.out, 'MEAN_RANK_K20.md'), 'w').write('\n'.join(md) + '\n')
    print(out.pivot_table(index='method', columns='backbone', values='mean_rank', sort=False).round(2).to_string())
    print('\n[rebuild_ranks] -> %s/: main_means_k20.csv, main_column_ranks_k20.csv, main_mean_rank_k20.csv, MEAN_RANK_K20.md' % a.out)


if __name__ == '__main__':
    main()
